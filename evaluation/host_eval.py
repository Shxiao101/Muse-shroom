def _gate(
    hits: int, total: int, threshold: tuple[int, int], *, kind: str,
) -> dict[str, Any]:
    numerator, denominator = threshold
    passed = total > 0 and hits * denominator >= total * numerator
    return {
        "kind": kind,
        "rate": _rate(hits, total),
        "threshold_ratio": f"{numerator}/{denominator}",
        "passed": passed,
        "decision": "GO" if passed else "NO-GO",
    }


def _recorded_call_count(attempt: Path) -> int:
    """Number of host tool calls recorded into an attempt."""
    transcript = attempt / "transcript.jsonl"
    if not transcript.is_file():
        return 0
    return sum(1 for line in transcript.read_text(encoding="utf-8").splitlines() if line.strip())


def _recorded_attempts(root: Path) -> list[Path]:
    """Attempts that recorded at least one host tool call, oldest first.

    An MCP client allocates an attempt whenever it launches or relaunches the
    recorder, including launches the host never uses. Such a directory holds an
    `attempt_started` event and nothing else: no host decision, no GitHub response,
    no result. It is an absence of measurement rather than a measurement, so it is
    neither classified nor treated as the newest attempt. Attempts that did record
    calls are never skipped, so a later failure can still not be bypassed.
    """
    return [
        item for item in sorted(root.glob("attempt-*"))
        if item.is_dir() and _recorded_call_count(item) > 0
    ]


def _select_development_attempt(
    root: Path, *, component_digest: str | None = None,
) -> dict[str, Any]:
    """Evaluate the newest recorded development attempt only; never fall back.

    Falling back to an older passing attempt would let a stale green shakedown
    authorise a holdout capture after a later red one.
    """
    if not root.is_dir():
        raise ValueError(f"development attempt root does not exist: {root}")
    attempts = _recorded_attempts(root)
    if not attempts:
        raise ValueError(
            f"no development attempt under {root} recorded any host tool call"
        )
    attempt = attempts[-1]
    manifest_path = attempt / "manifest.json"
    summary_path = attempt / "raw-summary.json"
    if not manifest_path.is_file() or not summary_path.is_file():
        raise ValueError(
            f"newest development attempt {attempt.name} is not summarized; "
            "summarize it before preparing or collecting a holdout"
        )
    manifest = _read_json(manifest_path)
    summary = _read_json(summary_path)

    if manifest.get("suite") != "development":
        raise ValueError(f"{attempt.name} is not a development attempt")
    for left, right, label in (
        (summary.get("attempt_id"), manifest.get("attempt_id"), "attempt_id"),
        (summary.get("suite_id"), manifest.get("suite_id"), "suite_id"),
        (summary.get("suite_digest"), manifest.get("suite_digest"), "suite_digest"),
        (
            summary.get("agent_visible_bundle_digest"),
            manifest.get("agent_visible_bundle_digest"),
            "agent_visible_bundle_digest",
        ),
        (
            summary.get("cassette_digest"),
            (manifest.get("cassette") or {}).get("sha256"),
            "cassette_digest",
        ),
    ):
        if left != right:
            raise ValueError(
                f"development attempt {attempt.name} manifest and summary disagree on {label}"
            )
    if manifest.get("capture_closed") is not True:
        raise ValueError(f"development attempt {attempt.name} did not close cleanly")
    if manifest.get("diagnostic_failures"):
        raise ValueError(
            f"development attempt {attempt.name} has diagnostic failures: "
            f"{manifest.get('diagnostic_failures')}"
        )
    expected = int(manifest.get("expected_case_count") or 0)
    completed = int(manifest.get("completed_case_count") or 0)
    if expected <= 0:
        raise ValueError(f"development attempt {attempt.name} has no prepared cases")
    if completed != expected:
        raise ValueError(
            f"development attempt {attempt.name} completed {completed} of {expected} cases"
        )
    if manifest.get("classification") != "capture_complete":
        raise ValueError(
            f"development attempt {attempt.name} is classified "
            f"{manifest.get('classification')!r}"
        )

    # The proposal rate is reported, never gated. A shakedown is a readiness report a
    # human reads; no rate may block a capture on its own.
    mechanical = summary.get("host_hypothesis_proposal_case_rate") or {}
    if int(mechanical.get("total") or 0) != expected:
        raise ValueError(
            f"development attempt {attempt.name} proposal rate denominator "
            f"{mechanical.get('total')!r} does not match {expected} prepared cases"
        )

    recorded_component = manifest.get("agent_visible_component_digest")
    if component_digest is not None:
        if not recorded_component:
            raise ValueError(
                f"development attempt {attempt.name} records no component digest; "
                "recapture the shakedown before preparing a holdout"
            )
        if recorded_component != component_digest:
            raise ValueError(
                "the Skill and production source changed after the development "
                f"shakedown: attempt {attempt.name} measured {recorded_component}, "
                f"holdout would run {component_digest}. Re-run the development "
                "shakedown against the current source."
            )
    return {
        "attempt_path": str(attempt),
        "attempt_id": manifest.get("attempt_id"),
        "suite_id": manifest.get("suite_id"),
        "suite_digest": manifest.get("suite_digest"),
        "agent_visible_bundle_digest": manifest.get("agent_visible_bundle_digest"),
        "agent_visible_component_digest": recorded_component,
        "source_revision": manifest.get("source_revision"),
        "expected_case_count": expected,
        "host_hypothesis_proposal_case_rate": dict(mechanical),
        "cases_without_hypothesis": list(summary.get("cases_without_hypothesis") or []),
    }


def _development_shakedown_ready(root: Path) -> tuple[bool, str]:
    """Tuple-returning wrapper over `_select_development_attempt`."""
    try:
        context = _select_development_attempt(root)
    except (OSError, ValueError, json.JSONDecodeError) as exc:
        return False, str(exc)
    return True, str(context["attempt_path"])


def _validate_holdout_capture_governance(
    root: Path, *, suite_id: str | None = None, suite_digest: str | None = None,
) -> None:
    """Permit another capture only after a sealed non-informative attempt."""
    if not root.exists():
        return
    for attempt in _recorded_attempts(root):
        manifest_path = attempt / "manifest.json"
        if not manifest_path.is_file():
            raise ValueError(
                f"holdout attempt {attempt.name} is not classified; summarize it before recapture"
            )
        manifest = _read_json(manifest_path)
        if manifest.get("suite") != "holdout":
            raise ValueError(f"non-holdout attempt found in holdout root: {attempt}")
        if suite_id and manifest.get("suite_id") != suite_id:
            raise ValueError("a new holdout suite must use a new attempt root")
        if suite_digest and manifest.get("suite_digest") != suite_digest:
            raise ValueError("a new holdout suite must use a new attempt root")
        # Only an incomplete capture may be retried. A capture that produced intact
        # artifacts has been observed, and re-running the same six cases would compare a
        # revised system against cases whose results are already known.
        if manifest.get("classification") != "capture_incomplete":
            raise ValueError(
                f"holdout suite cannot be recaptured after {manifest.get('classification')}: "
                f"{attempt.name}"
            )


def holdout_preflight(
    *,
    development_root: Path,
    component_digest: str,
) -> dict[str, Any]:
    """Bind a holdout attempt to the shakedown that measured the same source.

    The only hard requirement is that the newest development attempt is complete,
    intact, and ran against this exact `src/` and `skills/` state. No rate gates a
    capture: the proposal rate is reported for a human to read.

    This runs again at `collect`, against whichever development attempt is newest at
    that moment, so a failing shakedown sealed after `prepare` still blocks the capture.
    """
    return _select_development_attempt(
        development_root, component_digest=component_digest,
    )


def _suite_paths(suite: str) -> tuple[Path, Path]:
    if suite == "development":
        return DEFAULT_PROMPTS, DEFAULT_GOLDEN
    if suite == "holdout":
        return DEFAULT_HOLDOUT_PROMPTS, DEFAULT_HOLDOUT_GOLDEN
    raise ValueError(f"unknown host evaluation suite: {suite}")


def _concept_keys(concepts: list[dict[str, Any]]) -> set[str]:
    keys: set[str] = set()
    for concept in concepts:
        for raw in [concept.get("term"), *(concept.get("aliases") or [])]:
            key = _normalized(raw)
            if key:
                keys.add(key)
    return keys


def _golden_terms(path: Path) -> dict[str, list[str]]:
    payload = _read_json(path)
    terms: dict[str, list[str]] = {}
    for case in payload.get("cases") or []:
        case_id = str(case.get("id") or "")
        for concept in case.get("cross_mechanism_directions") or []:
            for raw in [concept.get("term"), *(concept.get("aliases") or [])]:
                key = _normalized(raw)
                if key:
                    terms.setdefault(key, []).append(case_id)
    return terms


def _bundle_leaks(bundle: Path, golden: Path) -> list[dict[str, Any]]:
    expected = _golden_terms(golden)
    leaks: list[dict[str, Any]] = []
    for path in sorted(item for item in bundle.rglob("*") if item.is_file()):
        if path.suffix.casefold() not in TEXT_SUFFIXES:
            continue
        try:
            text = _normalized(path.read_text(encoding="utf-8"))
        except UnicodeDecodeError:
            continue
        padded = f" {text} "
        for term, case_ids in expected.items():
            if term and f" {term} " in padded:
                leaks.append({
                    "term": term,
                    "path": path.relative_to(bundle).as_posix(),
                    "case_ids": sorted(set(case_ids)),
                })
    return leaks


def _mapping_path(bundle: Path) -> Path:
    return bundle.parent / f"{bundle.name}.case-map.json"


def _leakage_path(bundle: Path) -> Path:
    return bundle.parent / f"{bundle.name}.leakage.json"


def prepare(
    bundle: Path, *, suite: str = "development", prompts: Path | None = None,
    attempt_root: Path | None = None,
    development_root: Path = DEFAULT_DEVELOPMENT_ATTEMPT_ROOT,
) -> dict[str, Any]:
    """Create a fresh Agent-visible bundle and external mapping/leakage records."""
    default_prompts, golden = _suite_paths(suite)
    prompts = prompts or default_prompts
    mapping_path = _mapping_path(bundle)
    leakage_path = _leakage_path(bundle)
    for target in (bundle, mapping_path, leakage_path):
        if target.exists():
            raise FileExistsError(f"refusing to overwrite host-evaluation artifact: {target}")

    # The complete preflight runs before any bundle, attempt root, or attempt exists.
    development_gate: dict[str, Any] | None = None
    if suite == "holdout":
        development_gate = holdout_preflight(
            development_root=development_root,
            component_digest=_component_digest(ROOT),
        )

    payload = _read_json(prompts)
    golden_payload = _read_json(golden)
    golden_digest = _sha256_bytes(_canonical(golden_payload).encode("utf-8"))
    raw_cases = list(payload.get("prompts") or [])
    if not raw_cases:
        raise ValueError(f"host evaluation suite has no cases: {prompts}")
    mapping: dict[str, str] = {}
    anonymous: list[dict[str, Any]] = []
    for index, prompt in enumerate(raw_cases, start=1):
        anon_id = f"case-{index:02d}"
        real_id = str(prompt.get("id") or anon_id)
        request = prompt.get("request")
        if not isinstance(request, dict):
            raise ValueError(f"host evaluation case {real_id!r} has no request object")
        mapping[anon_id] = real_id
        anonymous.append({"id": anon_id, "request": request})
    suite_digest = _sha256_bytes(_canonical({
        "suite": suite, "cases": anonymous, "golden": golden_payload,
    }).encode("utf-8"))
    suite_id = f"{suite}-v{int(payload.get('schema_version') or 1)}-{suite_digest[:12]}"

    bundle.mkdir(parents=True)
    ignore = shutil.ignore_patterns("__pycache__", "*.pyc", "*.pyo", "*.egg-info")
    shutil.copytree(ROOT / "src", bundle / "src", ignore=ignore)
    shutil.copytree(ROOT / "skills", bundle / "skills", ignore=ignore)
    for name in ("pyproject.toml", "LICENSE", "README.md"):
        source = ROOT / name
        if source.exists():
            shutil.copy2(source, bundle / name)

    cases_payload = {
        "schema_version": 2, "suite": suite, "suite_id": suite_id,
        "suite_digest": suite_digest, "cases": anonymous,
    }
    _write_json_new(bundle / "cases.json", cases_payload)
    instructions = (
        "# Muse-shroom host evaluation\n\n"
        "Use only the generated Muse-shroom evaluation MCP server. Process every case in "
        "`cases.json` exactly once. For each case, call `muse_search` with the request object "
        "unchanged and `mode=deep`, then follow `next_action` through observe/iterate/rank. "
        "Use the production Skill in `skills/muse-shroom/`; do not invent "
        "repository queries or inspect files outside this bundle. Finish one case before "
        "starting the next. Golden answers are intentionally unavailable.\n"
    )
    (bundle / "HOST-RUN.md").write_text(instructions, encoding="utf-8", newline="\n")
    chosen_attempt_root = (attempt_root or (
        ROOT / "evaluation" / "results" / f"host-{suite}"
    )).resolve()
    collect_args = [
        str(Path(__file__).resolve()), "collect", "--bundle", str(bundle.resolve()),
        "--attempt-root", str(chosen_attempt_root),
    ]
    if development_gate is not None:
        collect_args += ["--development-root", str(Path(development_root).resolve())]
    mcp_config = {
        "mcpServers": {
            "muse-shroom-host-eval": {
                "command": sys.executable,
                "args": collect_args,
                "env": {
                    "MUSE_SHROOM_NO_EXPLORER": "1",
                    "PYTHONDONTWRITEBYTECODE": "1",
                },
            }
        }
    }
    _write_json_new(bundle / "mcp.json", mcp_config)
    bundle_digest = _directory_digest(bundle)
    _write_json_new(mapping_path, {
        "schema_version": 2, "suite": suite, "suite_id": suite_id,
        "suite_digest": suite_digest, "agent_visible_bundle_digest": bundle_digest,
        "golden_digest": golden_digest, "mapping": mapping,
    })
    leaks = _bundle_leaks(bundle, golden)
    leakage = {
        "schema_version": 2, "suite": suite, "suite_id": suite_id,
        "suite_digest": suite_digest, "agent_visible_bundle_digest": bundle_digest,
        "golden_digest": golden_digest,
        "release_eligible": False,
        "passed": not leaks, "leaks": leaks,
    }
    _write_json_new(leakage_path, leakage)
    if suite == "holdout" and leaks:
        raise ValueError(
            f"holdout bundle contains {len(leaks)} Golden direction leak(s); see {leakage_path}"
        )
    return {
        "bundle": str(bundle), "mapping": str(mapping_path),
        "leakage": str(leakage_path), "suite": suite,
        "suite_id": suite_id, "suite_digest": suite_digest,
        "agent_visible_bundle_digest": bundle_digest,
        "agent_visible_component_digest": _component_digest(bundle),
        "cases": len(anonymous),
        "development_gate": development_gate,
        "release_eligible": False,
    }


def _read_jsonl(path: Path) -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    if not path.exists():
        return rows
    for line_number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), start=1):
        if not line.strip():
            continue
        value = json.loads(line)
        if not isinstance(value, dict):
            raise ValueError(f"expected JSON object at {path}:{line_number}")
        rows.append(value)
    return rows


class RecordingAttempt:
    """Create-only host run that appends tool and lifecycle events until closed."""

    def __init__(
        self, bundle: Path, attempt_root: Path, *,
        development_root: Path = DEFAULT_DEVELOPMENT_ATTEMPT_ROOT,
    ) -> None:
        cases_payload = _read_json(bundle / "cases.json")
        self.bundle = bundle.resolve()
        self.suite = str(cases_payload.get("suite") or "")
        self.suite_id = str(cases_payload.get("suite_id") or "")
        self.suite_digest = str(cases_payload.get("suite_digest") or "")
        self.cases = list(cases_payload.get("cases") or [])
        if not self.suite or not self.suite_id or not self.suite_digest or not self.cases:
            raise ValueError("bundle cases.json is incomplete")
        leakage = _read_json(_leakage_path(bundle))
        current_digest = _directory_digest(bundle)
        if leakage.get("suite_digest") != self.suite_digest:
            raise ValueError("bundle and leakage report suite digests differ")
        if leakage.get("agent_visible_bundle_digest") != current_digest:
            raise ValueError("Agent-visible bundle changed after prepare")
        if self.suite == "holdout" and not leakage.get("passed"):
            raise ValueError("holdout bundle leakage check did not pass")

        self.component_digest = _component_digest(bundle)
        self.development_gate: dict[str, Any] | None = None
        if self.suite == "holdout":
            try:
                self.development_gate = holdout_preflight(
                    development_root=development_root,
                            component_digest=self.component_digest,
                )
            except ValueError as exc:
                raise ValueError(f"holdout capture requires development shakedown: {exc}") from exc
            _validate_holdout_capture_governance(
                attempt_root, suite_id=self.suite_id, suite_digest=self.suite_digest,
            )

        attempt_root.mkdir(parents=True, exist_ok=True)
        self.path = self._allocate(attempt_root)
        self.attempt_id = self.path.name
        self.data_dir = self.path / "data"
        self.data_dir.mkdir()
        self.cassette_path = self.path / "cassette.json.gz"
        self.events_path = self.path / "attempt-events.jsonl"
        self.transcript_path = self.path / "transcript.jsonl"
        self._lock = threading.RLock()
        self._sequence = 0
        self._closed = False
        self._github: Any | None = None
        self._delegate_store: Any | None = None
        self.search_cases: dict[str, str] = {}
        self.started_cases: set[str] = set()
        self.started_at = _utc_now()
        self._append(self.events_path, {
            "schema_version": 1, "event": "attempt_started", "at": self.started_at,
            "attempt_id": self.attempt_id, "suite": self.suite, "suite_id": self.suite_id,
            "suite_digest": self.suite_digest,
            "agent_visible_bundle_digest": current_digest,
            "agent_visible_component_digest": self.component_digest,
            "development_gate": self.development_gate,
            "bundle": str(self.bundle), "source_revision": _git_revision(),
            "source_dirty": _git_dirty(),
            "recorder_sha256": _sha256_file(Path(__file__).resolve()),
            "cassette_code_sha256": _sha256_file(ROOT / "evaluation" / "cassette.py"),
            "expected_case_ids": [str(item.get("id") or "") for item in self.cases],
        })

    @staticmethod
    def _allocate(root: Path) -> Path:
        for number in range(1, 10000):
            candidate = root / f"attempt-{number:02d}"
            try:
                candidate.mkdir()
            except FileExistsError:
                continue
            return candidate
        raise RuntimeError(f"no free host-evaluation attempt number under {root}")

    @staticmethod
    def _append(path: Path, payload: dict[str, Any]) -> None:
        with path.open("a", encoding="utf-8", newline="\n") as handle:
            handle.write(_canonical(_sanitize(payload)) + "\n")
            handle.flush()

    def attach_github(self, github: Any, delegate_store: Any | None = None) -> None:
        self._github = github
        self._delegate_store = delegate_store

    def case_for_request(self, request: dict[str, Any]) -> str:
        matches = [
            str(item.get("id") or "") for item in self.cases
            if _canonical(item.get("request")) == _canonical(request)
        ]
        if len(matches) != 1:
            raise ValueError("muse_search request must exactly match one prepared anonymous case")
        case_id = matches[0]
        if case_id in self.started_cases:
            raise ValueError(f"prepared case already started: {case_id}")
        return case_id

    def case_for_search(self, search_id: str) -> str:
        case_id = self.search_cases.get(search_id)
        if not case_id:
            raise ValueError("search_id was not created by this recording attempt")
        return case_id

    def bind_search(self, case_id: str, search_id: str) -> None:
        self.started_cases.add(case_id)
        self.search_cases[search_id] = case_id

    def record_tool(
        self, *, case_id: str | None, tool: str, arguments: dict[str, Any],
        output: Any | None = None, error: BaseException | None = None,
        search_id: str | None = None,
        github_activity: list[dict[str, Any]] | None = None,
    ) -> None:
        with self._lock:
            if self._closed:
                raise RuntimeError("recording attempt is already closed")
            self._sequence += 1
            payload: dict[str, Any] = {
                "schema_version": 1, "sequence": self._sequence, "at": _utc_now(),
                "attempt_id": self.attempt_id, "case_id": case_id, "tool": tool,
                "input": arguments, "search_id": search_id,
                "github_activity": list(github_activity or []),
            }
            if error is None:
                payload["output"] = output
            else:
                payload["error"] = {
                    "type": type(error).__name__, "message": str(error),
                }
            self._append(self.transcript_path, payload)
            self._append(self.events_path, {**payload, "event": "tool_call"})
            if self._github is not None:
                self._github.save()

    def close(self, *, process_error: BaseException | None = None) -> None:
        with self._lock:
            if self._closed:
                return
            cassette_error: BaseException | None = None
            try:
                if self._github is not None:
                    self._github.save()
            except BaseException as exc:  # Preserve the failed attempt before re-raising.
                cassette_error = exc
            finally:
                if self._delegate_store is not None:
                    self._delegate_store.close()
            self._append(self.events_path, {
                "schema_version": 1, "event": "attempt_closed", "at": _utc_now(),
                "attempt_id": self.attempt_id,
                "process_error": None if process_error is None else {
                    "type": type(process_error).__name__, "message": str(process_error),
                },
                "cassette_error": None if cassette_error is None else {
                    "type": type(cassette_error).__name__, "message": str(cassette_error),
                },
            })
            self._closed = True
            if cassette_error is not None:
                raise cassette_error


def _host_sdk():
    try:
        from mcp.server import MCPServer
        from mcp.server.mcpserver.exceptions import ToolError
        from mcp.types import ToolAnnotations
    except ImportError as exc:
        raise ImportError(
            "Host evaluation requires the MCP extra: pip install 'muse-shroom[mcp]'"
        ) from exc
    return MCPServer, ToolError, ToolAnnotations


def create_recording_server(
    bundle: Path, attempt_root: Path, *, github_delegate: Any | None = None,
    search_interval: float = 3.5,
    development_root: Path = DEFAULT_DEVELOPMENT_ATTEMPT_ROOT,
    recording_attempt: RecordingAttempt | None = None,
) -> tuple[Any, RecordingAttempt]:
    """Create a real Muse-shroom MCP server wrapped by a create-only recorder."""
    attempt = recording_attempt or RecordingAttempt(
        bundle, attempt_root, development_root=development_root,
    )
    sys.dont_write_bytecode = True
    source_path = str(bundle.resolve() / "src")
    if source_path not in sys.path:
        sys.path.insert(0, source_path)
    evaluation_path = str(ROOT / "evaluation")
    if evaluation_path not in sys.path:
        sys.path.insert(0, evaluation_path)

    from cassette import CassetteGitHub
    from muse_shroom import __version__
    from muse_shroom import github as github_module
    from muse_shroom.auth import AuthError
    from muse_shroom.github import GitHubError
    from muse_shroom.mcp_schema import (
        HOST_INSTRUCTIONS, MUSE_ITERATE_DESCRIPTION, MUSE_RANK_DESCRIPTION,
        MUSE_SEARCH_DESCRIPTION, publish_agent_schemas,
    )
    from muse_shroom.models import ContractError
    from muse_shroom.services import MuseCore
    from muse_shroom.storage import Store

    delegate_store = None
    if github_delegate is None:
        delegate_store = Store(attempt.data_dir)
        attempt.attach_github(None, delegate_store)

        class LazyGitHubClient:
            """Defer credential lookup until the host actually calls a GitHub tool."""

            def __init__(self) -> None:
                self.client: Any | None = None

            def __getattr__(self, name: str) -> Any:
                if self.client is None:
                    self.client = github_module.GitHubClient(delegate_store)
                return getattr(self.client, name)

        github_delegate = LazyGitHubClient()
    github = CassetteGitHub(
        github_module, attempt.cassette_path, delegate=github_delegate,
        search_interval=search_interval, serial_capture=True, auto_save=True,
    )
    attempt.attach_github(github, delegate_store)
    os.environ.setdefault("MUSE_SHROOM_NO_EXPLORER", "1")
    core = MuseCore(data_dir=str(attempt.data_dir), github=github)
    MCPServer, ToolError, ToolAnnotations = _host_sdk()
    server = MCPServer(
        "muse-shroom-host-eval", version=__version__,
        log_level="ERROR",
        instructions=(
            HOST_INSTRUCTIONS
            + " Host evaluation: use each exact request in cases.json once in Deep mode."
        ),
    )
    read_only = ToolAnnotations(read_only_hint=True, open_world_hint=False)
    local_write = ToolAnnotations(read_only_hint=False, open_world_hint=False)
    github_write = ToolAnnotations(read_only_hint=False, open_world_hint=True)
    known_errors = (ContractError, AuthError, GitHubError, KeyError, ValueError)

    def invoke(
        tool: str, arguments: dict[str, Any], fn: Callable[[], dict[str, Any]],
        *, case_id: str | None, search_id: str | None = None,
    ) -> dict[str, Any]:
        github_cursor = github.diagnostic_cursor()
        try:
            output = fn()
        except known_errors as exc:
            attempt.record_tool(
                case_id=case_id, tool=tool, arguments=arguments,
                error=exc, search_id=search_id,
                github_activity=github.diagnostics_since(github_cursor),
            )
            raise ToolError(f"{type(exc).__name__}: {_sanitize(str(exc))}") from exc
        attempt.record_tool(
            case_id=case_id, tool=tool, arguments=arguments,
            output=output, search_id=search_id or str(output.get("search_id") or "") or None,
            github_activity=github.diagnostics_since(github_cursor),
        )
        return output

    @server.tool(annotations=github_write, description=MUSE_SEARCH_DESCRIPTION)
    def muse_search(
        request: dict[str, Any], mode: Literal["quick", "deep"] = "quick",
        refresh: bool = False,
    ) -> dict[str, Any]:
        arguments = {"request": request, "mode": mode, "refresh": refresh}
        case_id: str | None = None
        try:
            case_id = attempt.case_for_request(request)
            if mode != "deep":
                raise ContractError("host evaluation requires mode=deep")
        except known_errors as exc:
            attempt.record_tool(case_id=case_id, tool="muse_search", arguments=arguments, error=exc)
            raise ToolError(f"{type(exc).__name__}: {_sanitize(str(exc))}") from exc
        output = invoke(
            "muse_search", arguments,
            lambda: core.search(request, mode, refresh=refresh), case_id=case_id,
        )
        attempt.bind_search(case_id, str(output["search_id"]))
        return output

    @server.tool(annotations=read_only)
    def muse_observe(search_id: str) -> dict[str, Any]:
        """Read-only restore of a recorded search session."""
        arguments = {"search_id": search_id}
        try:
            case_id = attempt.case_for_search(search_id)
        except known_errors as exc:
            attempt.record_tool(case_id=None, tool="muse_observe", arguments=arguments, error=exc)
            raise ToolError(f"{type(exc).__name__}: {_sanitize(str(exc))}") from exc
        return invoke(
            "muse_observe", arguments, lambda: core.observe(search_id),
            case_id=case_id, search_id=search_id,
        )

    @server.tool(annotations=github_write, description=MUSE_ITERATE_DESCRIPTION)
    def muse_iterate(search_id: str, hypothesis: dict[str, Any]) -> dict[str, Any]:
        arguments = {"search_id": search_id, "hypothesis": hypothesis}
        try:
            case_id = attempt.case_for_search(search_id)
        except known_errors as exc:
            attempt.record_tool(case_id=None, tool="muse_iterate", arguments=arguments, error=exc)
            raise ToolError(f"{type(exc).__name__}: {_sanitize(str(exc))}") from exc
        return invoke(
            "muse_iterate", arguments, lambda: core.iterate(search_id, hypothesis),
            case_id=case_id, search_id=search_id,
        )

    @server.tool(annotations=local_write, description=MUSE_RANK_DESCRIPTION)
    def muse_rank(search_id: str, selection: list[dict[str, Any]]) -> dict[str, Any]:
        arguments = {"search_id": search_id, "selection": selection}
        try:
            case_id = attempt.case_for_search(search_id)
        except known_errors as exc:
            attempt.record_tool(case_id=None, tool="muse_rank", arguments=arguments, error=exc)
            raise ToolError(f"{type(exc).__name__}: {_sanitize(str(exc))}") from exc

        return invoke(
            "muse_rank", arguments, lambda: core.rank(search_id, selection),
            case_id=case_id, search_id=search_id,
        )

    publish_agent_schemas(server)
    return server, attempt


def run_collect(
    bundle: Path, attempt_root: Path, *, search_interval: float = 3.5,
    development_root: Path = DEFAULT_DEVELOPMENT_ATTEMPT_ROOT,
) -> Path:
    attempt = RecordingAttempt(
        bundle, attempt_root, development_root=development_root,
    )
    print(
        json.dumps({"attempt": str(attempt.path), "status": "recording"}, ensure_ascii=False),
        file=sys.stderr, flush=True,
    )
    process_error: BaseException | None = None
    try:
        server, _attempt = create_recording_server(
            bundle, attempt_root, search_interval=search_interval,
            development_root=development_root, recording_attempt=attempt,
        )
        server.run()
    except BaseException as exc:
        process_error = exc
        raise
    finally:
        attempt.close(process_error=process_error)
    return attempt.path


def _golden_directions(golden: dict[str, Any], case_id: str) -> list[dict[str, Any]]:
    for case in golden.get("cases") or []:
        if str(case.get("id") or "") == case_id:
            return list(case.get("cross_mechanism_directions") or [])
    return []


def _matching_evidence(record: dict[str, Any], candidates: list[dict[str, Any]]) -> list[str]:
    hypothesis_id = str(record.get("id") or "")
    term = _normalized(record.get("term"))
    matches: list[str] = []
    for candidate in candidates:
        repo = str(candidate.get("full_name") or "")
        for evidence in candidate.get("evidence") or []:
            facts = evidence.get("facts") or {}
            mechanisms = facts.get("mechanisms") or []
            if (
                evidence.get("kind") == "mechanism_match"
                and facts.get("semantic_origin") is True
                and str(facts.get("hypothesis_id") or "") == hypothesis_id
                and any(_normalized(item.get("name")) == term for item in mechanisms)
            ):
                matches.append(repo)
                break
    return sorted(set(matches))


def _merge_counts(dicts: Any) -> dict[str, int]:
    merged: dict[str, int] = {}
    for item in dicts:
        for key, value in (item or {}).items():
            merged[str(key)] = merged.get(str(key), 0) + int(value)
    return dict(sorted(merged.items()))


def _rank_outcome(events: list[dict[str, Any]]) -> dict[str, Any]:
    """Summarise what happened to the Agent's selections in this case.

    A case counts as completed once any `muse_rank` returned output, so a run where
    every item failed verification looks complete unless the rejections are reported.
    """
    ranks = [item for item in events if item.get("tool") == "muse_rank" and item.get("output")]
    reasons: dict[str, int] = {}
    for item in ranks:
        for entry in (item.get("output") or {}).get("rejected_items") or []:
            for reason in entry.get("reasons") or []:
                key = str(reason).split(":", 1)[0]
                reasons[key] = reasons.get(key, 0) + 1
    final = (ranks[-1].get("output") or {}) if ranks else {}
    return {
        "rank_calls": len(ranks),
        "selection_accepted": len(final.get("items") or []),
        "selection_rejected": len(final.get("rejected_items") or []),
        # True when the Agent stopped on a rank that accepted nothing.
        "ended_with_empty_selection": bool(ranks) and not (final.get("items") or []),
        "rejection_reasons": reasons,
    }


def classify_attempt(
    suite: str, *, malformed_reasons: list[str],
) -> tuple[str, str, bool]:
    """Classify a capture by whether it completed, never by what it found.

    Outcome classifications keyed to a model-authored answer key were removed: agreement
    with such a key cannot authorise anything, so it must not label a capture either.
    What remains is a fact — did the recorder produce intact artifacts.
    """
    if malformed_reasons:
        return "capture_incomplete", "capture_infrastructure_failure", False
    return "capture_complete", "artifacts_intact", True


def summarize_attempt(attempt: Path, *, mapping_path: Path, suite: str) -> dict[str, Any]:
    """Classify one capture before exposing any case-level diagnostics."""
    manifest_path = attempt / "manifest.json"
    summary_path = attempt / "raw-summary.json"
    if manifest_path.exists() or summary_path.exists():
        raise FileExistsError("attempt was already summarized and is sealed")
    lifecycle = _read_jsonl(attempt / "attempt-events.jsonl")
    transcript = _read_jsonl(attempt / "transcript.jsonl")
    if not lifecycle or lifecycle[0].get("event") != "attempt_started":
        raise ValueError("attempt has no start event")
    started = lifecycle[0]
    if started.get("suite") != suite:
        raise ValueError("requested suite does not match the attempt")
    mapping_payload = _read_json(mapping_path)
    if mapping_payload.get("suite_digest") != started.get("suite_digest"):
        raise ValueError("case mapping does not match the attempt suite")
    if mapping_payload.get("suite_id") != started.get("suite_id"):
        raise ValueError("case mapping suite identity does not match the attempt")
    if (
        mapping_payload.get("agent_visible_bundle_digest")
        != started.get("agent_visible_bundle_digest")
    ):
        raise ValueError("case mapping bundle digest does not match the attempt")
    mapping = dict(mapping_payload.get("mapping") or {})
    _prompts, golden_path = _suite_paths(suite)
    golden = _read_json(golden_path)
    current_golden_digest = _sha256_bytes(_canonical(golden).encode("utf-8"))
    if mapping_payload.get("golden_digest") != current_golden_digest:
        raise ValueError("Golden cases changed after the Agent-visible bundle was prepared")

    malformed_reasons: list[str] = []
    sequences = [item.get("sequence") for item in transcript]
    if sequences != list(range(1, len(transcript) + 1)):
        malformed_reasons.append("transcript_sequence_gap")
    closed = next((item for item in reversed(lifecycle) if item.get("event") == "attempt_closed"), None)
    # MCP clients normally terminate a stdio server rather than shutting it down, so
    # `attempt.close()` often never runs and no close event is written. Termination is
    # the ordinary path, not a defect: the cassette is saved after every recorded call,
    # so a terminated capture still leaves complete artifacts up to its last call.
    # Treat the capture as ended when it has gone quiet, and record how it ended.
    if closed is not None:
        close_kind = "graceful"
        if closed.get("process_error") or closed.get("cassette_error"):
            close_kind = "failed"
            malformed_reasons.append("capture_closed_with_error")
    else:
        idle = time.time() - (attempt / "attempt-events.jsonl").stat().st_mtime
        if idle < CAPTURE_QUIESCE_SECONDS:
            raise ValueError(
                f"attempt {attempt.name} was written to {idle:.0f}s ago and has no close "
                f"event; stop the host and its MCP server, then summarize after "
                f"{CAPTURE_QUIESCE_SECONDS}s of quiet"
            )
        close_kind = "terminated"
    if any(item.get("error") for item in transcript):
        malformed_reasons.append("tool_error_recorded")
    if _contains_secret(lifecycle) or _contains_secret(transcript):
        malformed_reasons.append("credential_material_recorded")

    expected_ids = list(started.get("expected_case_ids") or [])
    golden_ids = {
        str(case.get("id") or "") for case in golden.get("cases") or []
        if str(case.get("id") or "")
    }
    if (
        set(mapping) != set(expected_ids)
        or any(not str(value) or str(value) not in golden_ids for value in mapping.values())
        or len(set(str(value) for value in mapping.values())) != len(expected_ids)
    ):
        malformed_reasons.append("case_mapping_mismatch")
    by_case: dict[str, list[dict[str, Any]]] = {case_id: [] for case_id in expected_ids}
    for event in transcript:
        case_id = str(event.get("case_id") or "")
        if case_id not in by_case:
            malformed_reasons.append("unknown_or_unassigned_case")
            continue
        by_case[case_id].append(event)
    completed_ids = [
        case_id for case_id, events in by_case.items()
        if any(item.get("tool") == "muse_search" and item.get("output") for item in events)
        and any(item.get("tool") == "muse_rank" and item.get("output") for item in events)
    ]
    if len(completed_ids) != len(expected_ids):
        malformed_reasons.append("incomplete_cases")

    try:
        try:
            from evaluation.cassette import load_cassette
        except ModuleNotFoundError:
            from cassette import load_cassette
        cassette = load_cassette(attempt / "cassette.json.gz")
    except (OSError, ValueError, json.JSONDecodeError) as exc:
        cassette = {"calls": {}, "capture_diagnostics": []}
        malformed_reasons.append(f"cassette_unreadable:{type(exc).__name__}")
    calls = cassette.get("calls") or {}
    if not isinstance(calls, dict) or any(
        not isinstance(item, dict) or "request" not in item or "response" not in item
        for item in calls.values()
    ):
        malformed_reasons.append("cassette_not_closed")
    diagnostics = list(cassette.get("capture_diagnostics") or [])
    search_starts = [
        item for item in diagnostics
        if item.get("event") == "search_started" and item.get("monotonic") is not None
    ]
    intervals = [
        float(right["monotonic"]) - float(left["monotonic"])
        for left, right in zip(search_starts, search_starts[1:])
    ]
    if any(
        value + 0.001 < float(left.get("interval") or 0)
        for value, left in zip(intervals, search_starts)
    ):
        malformed_reasons.append("search_pacing_violation")

    sys.path.insert(0, str(ROOT / "src")) if str(ROOT / "src") not in sys.path else None
    from muse_shroom.sidecar import public_hypothesis
    from muse_shroom.storage import Store
    store = Store(attempt / "data")
    case_rows: list[dict[str, Any]] = []
    try:
        for anon_id in expected_ids:
            real_id = str(mapping.get(anon_id) or "")
            directions = _golden_directions(golden, real_id)
            wanted = _concept_keys(directions)
            events = by_case.get(anon_id) or []
            search_event = next((item for item in events if item.get("tool") == "muse_search" and item.get("output")), None)
            search_id = str(((search_event or {}).get("output") or {}).get("search_id") or "")
            records: list[dict[str, Any]] = []
            candidates: list[dict[str, Any]] = []
            metrics: dict[str, Any] = {}
            sidecar: dict[str, Any] = {}
            if search_id:
                try:
                    state = store.get_session_state(search_id)
                    session = store.load_search(search_id)
                except KeyError:
                    malformed_reasons.append("missing_session_state")
                else:
                    sidecar = state.get("semantic_sidecar") or {}
                    records = list(sidecar.get("hypotheses") or [])
                    metrics = dict(sidecar.get("metrics") or {})
                    candidates = list(session.get("candidates") or [])
            # Suite-independent: the chain is measured over every hypothesis the Agent
            # proposed. Whether a term matches an answer key says nothing about whether
            # the pipeline carried it to evidence and into the Agent's selection.
            evidence_records = [
                record for record in records if _matching_evidence(record, candidates)
            ]
            executed_records = [
                record for record in records
                if any(item.get("executed") for item in record.get("queries") or [])
            ]
            selected_records = [record for record in records if record.get("validated")]
            presented_records = [record for record in records if record.get("presented")]
            record_queries = [
                query for record in records for query in record.get("queries") or []
            ]
            semantic_query_texts = {
                str(query.get("query") or "") for query in record_queries
                if str(query.get("query") or "")
            }
            sidecar_activity: list[dict[str, Any]] = []
            for event in events:
                activity = list(event.get("github_activity") or [])
                semantic_sequences = []
                for item in activity:
                    if item.get("method") != "search_repositories":
                        continue
                    key = str(item.get("request_key") or "")
                    request_record = calls.get(key) or {}
                    request = request_record.get("request") or item.get("request") or {}
                    args = list(request.get("args") or [])
                    if args and str(args[0]) in semantic_query_texts:
                        semantic_sequences.append(int(item.get("request_sequence") or 0))
                if semantic_sequences:
                    first_semantic = min(semantic_sequences)
                    sidecar_activity.extend([
                        item for item in activity
                        if int(item.get("request_sequence") or 0) >= first_semantic
                        or item.get("event") in {"throttle_wait", "rate_limit_wait"}
                    ])
            planned_queries = len(record_queries)
            executed_queries = sum(bool(query.get("executed")) for query in record_queries)
            skipped_queries = sum(bool(query.get("skipped")) for query in record_queries)
            failed_queries = sum(
                1 for record in records if record.get("failed")
                for query in record.get("queries") or []
                if not query.get("executed") and not query.get("skipped")
            )
            case_rows.append({
                "case_id": real_id, "anonymous_id": anon_id, "search_id": search_id,
                "completed": anon_id in completed_ids,
                **_rank_outcome(events),
                "iterations": sum(
                    1 for item in events
                    if item.get("tool") == "muse_iterate" and item.get("output")
                ),
                "host_hypotheses": [public_hypothesis(item) for item in records],
                "host_hypotheses_proposed": len(records),
                "hypothesis_terms": [str(item.get("term") or "") for item in records],
                "query_executed_hit": bool(executed_records),
                "evidence_found_hit": bool(evidence_records),
                "agent_selected_hit": bool(selected_records),
                "presented_hit": bool(presented_records),
                "semantic_queries": {
                    "planned": planned_queries, "executed": executed_queries,
                    "api_attempts": sum(
                        item.get("event") == "api_attempt"
                        and item.get("outcome") == "started"
                        and item.get("method") == "search_repositories"
                        for item in sidecar_activity
                    ),
                    "skipped": skipped_queries, "failed": failed_queries,
                },
                "semantic_candidates": len(sidecar.get("candidates") or []) if search_id else 0,
                "semantic_enrichment": {
                    "readme_attempts": sum(
                        item.get("event") == "api_attempt"
                        and item.get("outcome") == "started"
                        and item.get("method") == "readme"
                        for item in sidecar_activity
                    ),
                    "readme_succeeded": int(metrics.get("semantic_readme_enrichments") or 0),
                    "release_attempts": sum(
                        item.get("event") == "api_attempt"
                        and item.get("outcome") == "started"
                        and item.get("method") == "latest_release"
                        for item in sidecar_activity
                    ),
                    "release_succeeded": int(metrics.get("semantic_release_lookups") or 0),
                },
                "matching_evidence": [
                    {"hypothesis_id": item.get("id"), "repos": _matching_evidence(item, candidates)}
                    for item in evidence_records
                ],
                "sidecar_metrics": metrics,
            })
    finally:
        store.close()

    malformed_reasons = sorted(set(malformed_reasons))
    total = len(expected_ids)
    query_hits = sum(bool(item["query_executed_hit"]) for item in case_rows)
    evidence_hits = sum(bool(item["evidence_found_hit"]) for item in case_rows)
    selected_hits = sum(bool(item["agent_selected_hit"]) for item in case_rows)
    presented_hits = sum(bool(item["presented_hit"]) for item in case_rows)
    hypotheses = sum(int(item["host_hypotheses_proposed"]) for item in case_rows)
    query_totals = {
        key: sum(int((item.get("semantic_queries") or {}).get(key) or 0) for item in case_rows)
        for key in ("planned", "executed", "api_attempts", "skipped", "failed")
    }
    enrichment_totals = {
        key: sum(int((item.get("semantic_enrichment") or {}).get(key) or 0) for item in case_rows)
        for key in (
            "readme_attempts", "readme_succeeded", "release_attempts", "release_succeeded",
        )
    }

    api_attempts = [item for item in diagnostics if item.get("event") == "api_attempt"]
    api_waits = [
        item for item in diagnostics
        if item.get("event") in {"throttle_wait", "rate_limit_wait"}
    ]
    api_outcomes = [item for item in diagnostics if item.get("event") == "api_outcome"]
    started_attempts = {
        (item.get("request_sequence"), item.get("attempt"))
        for item in api_attempts if item.get("outcome") == "started"
    }
    terminal_attempts = {
        (item.get("request_sequence"), item.get("attempt"))
        for item in api_attempts if item.get("outcome") in {"succeeded", "rate_limited", "failed"}
    }
    if started_attempts != terminal_attempts:
        malformed_reasons.append("github_attempt_without_terminal_outcome")
    request_sequences = {
        item.get("request_sequence") for item in diagnostics
        if item.get("request_sequence") is not None
    }
    terminal_requests = {
        item.get("request_sequence") for item in api_outcomes
        if item.get("request_sequence") is not None
    }
    if request_sequences - terminal_requests:
        malformed_reasons.append("github_request_without_terminal_outcome")
    malformed_reasons = sorted(set(malformed_reasons))

    proposal_case_hits = sum(
        1 for item in case_rows if int(item["host_hypotheses_proposed"]) > 0
    )
    cases_without_hypothesis = [
        str(item["case_id"]) for item in case_rows
        if int(item["host_hypotheses_proposed"]) == 0
    ]
    proposal_rate = _rate(proposal_case_hits, total)
    classification, reason, expose_cases = classify_attempt(
        suite, malformed_reasons=malformed_reasons,
    )

    cassette_path = attempt / "cassette.json.gz"
    transcript_path = attempt / "transcript.jsonl"
    manifest = {
        "schema_version": 2, "attempt_id": attempt.name,
        "suite": suite, "suite_id": started.get("suite_id"),
        "suite_digest": started.get("suite_digest"),
        "agent_visible_bundle_digest": started.get("agent_visible_bundle_digest"),
        "agent_visible_component_digest": started.get("agent_visible_component_digest"),
        "development_gate": started.get("development_gate"),
        "source_revision": started.get("source_revision"),
        "source_dirty": started.get("source_dirty"),
        "recorder_sha256": started.get("recorder_sha256"),
        "cassette_code_sha256": started.get("cassette_code_sha256"),
        "started_at": started.get("at"), "completed_at": (closed or {}).get("at"),
        "expected_case_count": total, "completed_case_count": len(completed_ids),
        "capture_closed": close_kind in {"graceful", "terminated"},
        "close_kind": close_kind,
        "governance": "six_case_one_shot" if suite == "holdout" else "development_unrestricted",
        "classification": classification, "classification_reason": reason,
        "case_level_summary_included": expose_cases,
        "host_hypothesis_proposal_case_rate": proposal_rate,
        "cases_without_hypothesis": cases_without_hypothesis if expose_cases else [],
        "cassette": {
            "name": cassette_path.name, "bytes": cassette_path.stat().st_size if cassette_path.exists() else 0,
            "sha256": _sha256_file(cassette_path), "call_count": len(calls),
        },
        "transcript": {
            "name": transcript_path.name, "bytes": transcript_path.stat().st_size if transcript_path.exists() else 0,
            "sha256": _sha256_file(transcript_path), "event_count": len(transcript),
        },
        "diagnostic_failures": malformed_reasons,
        "release_eligible": False,
    }
    summary: dict[str, Any] = {
        "schema_version": 2, "attempt_id": attempt.name, "suite": suite,
        "suite_id": started.get("suite_id"), "suite_digest": started.get("suite_digest"),
        "agent_visible_bundle_digest": started.get("agent_visible_bundle_digest"),
        "agent_visible_component_digest": started.get("agent_visible_component_digest"),
        "development_gate": started.get("development_gate"),
        "capture_revision": started.get("source_revision"),
        "cassette_digest": _sha256_file(cassette_path),
        "classification": classification, "classification_reason": reason,
        "host_hypothesis_proposal_case_rate": proposal_rate,
        "cases_without_hypothesis": cases_without_hypothesis if expose_cases else [],
        # hypothesis -> executed query -> evidence found -> selected by the Agent ->
        # displayed. Every link is a fact about this run, with no answer key involved.
        "pipeline_rates": {
            "executed_query": _rate(query_hits, total),
            "matching_evidence": _rate(evidence_hits, total),
            "agent_selected": _rate(selected_hits, total),
            "presented": _rate(presented_hits, total),
        },
        "host_hypotheses_proposed": hypotheses,
        "selection": {
            "accepted": sum(int(item["selection_accepted"]) for item in case_rows),
            "rejected": sum(int(item["selection_rejected"]) for item in case_rows),
            "rank_calls": sum(int(item["rank_calls"]) for item in case_rows),
            "cases_ending_empty": sum(
                bool(item["ended_with_empty_selection"]) for item in case_rows
            ),
            "rejection_reasons": _merge_counts(
                item["rejection_reasons"] for item in case_rows
            ),
        },
        "iterations": _merge_counts(
            {str(item["iterations"]): 1} for item in case_rows
        ),
        "semantic_queries": query_totals,
        "semantic_candidates": sum(int(item.get("semantic_candidates") or 0) for item in case_rows),
        "semantic_enrichment": enrichment_totals,
        "github_api": {
            "attempts": len([item for item in api_attempts if item.get("outcome") == "started"]),
            "waits": len(api_waits),
            "wait_seconds": round(sum(float(item.get("seconds") or 0) for item in api_waits), 3),
            "failures": len([
                item for item in api_outcomes if item.get("outcome") in {"error", "not_found"}
            ]),
            "outcomes": {
                outcome: sum(item.get("outcome") == outcome for item in api_outcomes)
                for outcome in ("result", "not_found", "error", "cassette_hit")
            },
        },
        "capture": {
            "completed_cases": len(completed_ids), "expected_cases": total,
            "cassette_calls": len(calls), "search_intervals": [round(value, 3) for value in intervals],
            "diagnostic_failures": malformed_reasons,
        },
        "case_level_summary_included": expose_cases,
        "cases": case_rows if expose_cases else [],
        "release_eligible": False,
    }
    if _contains_secret(manifest) or _contains_secret(summary):
        raise ValueError("refusing to write host-evaluation artifacts containing credentials")
    _write_json_new(summary_path, summary)
    _write_json_new(manifest_path, manifest)
    return summary


# Legacy scorer retained for compatibility. It is not a release gate; the release
# decision comes from the matched blind A/B in evaluation/ab-protocol.md.
def score_case(result: dict[str, Any], directions: list[dict[str, Any]]) -> dict[str, Any]:
    wanted = _concept_keys(directions)
    hypotheses = list(result.get("semantic_hypotheses") or [])
    proposed = [str(item.get("term") or "") for item in hypotheses]
    golden_proposed = [
        term for term in proposed if _normalized(term) in wanted
        or any(_normalized(term) == key for key in wanted)
        or any(key in f" {_normalized(term)} " or _normalized(term) in key for key in wanted)
    ]
    queries = [
        query for item in hypotheses for query in item.get("queries") or []
        if query.get("executed")
    ]
    golden_queries = [
        query for query in queries
        if any(key in _normalized(query.get("query")) for key in wanted)
    ]
    evidence = [
        item for item in hypotheses
        if item.get("status") in {"evidence_found", "validated", "presented"}
        or item.get("evidence_repos")
    ]
    golden_evidence = [
        item for item in evidence
        if _normalized(item.get("term")) in wanted
        or any(key in _normalized(item.get("term")) for key in wanted)
    ]
    return {
        "host_hypotheses_proposed": len(hypotheses),
        "golden_cross_domain_hypotheses_proposed": len(golden_proposed),
        "pure_and_bridge_queries_executed": len(queries),
        "golden_direction_queries_executed": len(golden_queries),
        "mechanism_evidence_found": len(evidence),
        "golden_mechanism_evidence_found": len(golden_evidence),
        "validated": sum(1 for item in hypotheses if item.get("status") in {"validated", "presented"}),
        "presented": sum(1 for item in hypotheses if item.get("presented") or item.get("status") == "presented"),
        "capability_query_hit": bool(golden_queries),
        "capability_evidence_hit": bool(golden_evidence),
    }


def score(
    collect_path: Path, *, mapping_path: Path | None,
    golden: Path = DEFAULT_GOLDEN, holdout_golden: Path = DEFAULT_HOLDOUT_GOLDEN,
    disabled_path: Path | None = None,
) -> dict[str, Any]:
    """Legacy score kept for older collect artifacts. Gates nothing."""
    payload = _read_json(collect_path)
    golden_payload = _read_json(golden)
    mapping = {}
    if mapping_path and mapping_path.exists():
        mapping = _read_json(mapping_path).get("mapping") or {}
    cases = []
    for result in payload.get("results") or []:
        anon_id = str(result.get("case_id") or "")
        real_id = mapping.get(anon_id, anon_id)
        directions = _golden_directions(golden_payload, real_id)
        scored = score_case(result, directions)
        scored["case_id"] = real_id
        scored["anonymous_id"] = anon_id
        scored["sidecar_metrics"] = result.get("sidecar_metrics") or {}
        cases.append(scored)
    query_hits = sum(1 for item in cases if item["capability_query_hit"])
    evidence_hits = sum(1 for item in cases if item["capability_evidence_hit"])
    no_can = None
    if disabled_path and disabled_path.exists():
        no_can = compare_no_cannibalization(payload, _read_json(disabled_path))
    gate = {
        "valid_transcript": bool(cases),
        "no_cannibalization_passed": None if no_can is None else bool(no_can.get("passed")),
        "development_query_hit": query_hits >= 1,
        "development_evidence_hit": evidence_hits >= 1,
    }
    gate["passed"] = (
        gate["valid_transcript"]
        and gate["development_query_hit"]
        and gate["development_evidence_hit"]
        and (gate["no_cannibalization_passed"] is not False)
    )
    return {
        "schema_version": 1, "cases": cases,
        "aggregate": {
            "query_hits": query_hits, "evidence_hits": evidence_hits,
            "host_hypotheses_proposed": sum(item["host_hypotheses_proposed"] for item in cases),
        },
        "no_cannibalization": no_can, "capability_gate": gate,
        "observational": {
            "holdout_discovery_metrics": "not_scored_here",
            "development_aggregate_quality": "observational",
        },
    }


def compare_no_cannibalization(enabled: dict[str, Any], disabled: dict[str, Any]) -> dict[str, Any]:
    """Compare the exact base query/budget ledger for every matched phase."""
    from muse_shroom.sidecar import compare_base_ledgers

    diffs: list[dict[str, Any]] = []
    enabled_by = {str(item.get("case_id")): item for item in enabled.get("results") or []}
    disabled_by = {str(item.get("case_id")): item for item in disabled.get("results") or []}
    for case_id, enabled_item in enabled_by.items():
        other = disabled_by.get(case_id)
        if other is None:
            diffs.append({"case_id": case_id, "fields": ["missing_disabled_case"]})
            continue
        left_ledger = (enabled_item.get("sidecar_metrics") or {}).get("base_ledger")
        right_ledger = (other.get("sidecar_metrics") or {}).get("base_ledger")
        if not isinstance(left_ledger, list) or not isinstance(right_ledger, list):
            changed = ["missing_base_ledger"]
        else:
            changed = compare_base_ledgers(left_ledger, right_ledger)
        if changed:
            diffs.append({"case_id": case_id, "fields": changed})
    return {"passed": not diffs, "diffs": diffs}


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="Host evaluation prepare / record / summarize")
    sub = parser.add_subparsers(dest="command", required=True)

    prepare_cmd = sub.add_parser("prepare")
    prepare_cmd.add_argument("--bundle", type=Path, required=True)
    prepare_cmd.add_argument("--suite", choices=("development", "holdout"), default="development")
    prepare_cmd.add_argument("--prompts", type=Path)
    prepare_cmd.add_argument("--attempt-root", type=Path)
    prepare_cmd.add_argument(
        "--development-root", type=Path, default=DEFAULT_DEVELOPMENT_ATTEMPT_ROOT,
    )

    collect_cmd = sub.add_parser("collect")
    collect_cmd.add_argument("--bundle", type=Path, required=True)
    collect_cmd.add_argument("--attempt-root", type=Path, required=True)
    collect_cmd.add_argument("--search-interval", type=float, default=3.5)
    collect_cmd.add_argument(
        "--development-root", type=Path, default=DEFAULT_DEVELOPMENT_ATTEMPT_ROOT,
    )

    summary_cmd = sub.add_parser("summarize")
    summary_cmd.add_argument("--attempt", type=Path, required=True)
    summary_cmd.add_argument("--mapping", type=Path, required=True)
    summary_cmd.add_argument("--suite", choices=("development", "holdout"), required=True)

    score_cmd = sub.add_parser("score")
    score_cmd.add_argument("--collect", type=Path, required=True)
    score_cmd.add_argument("--mapping", type=Path)
    score_cmd.add_argument("--golden", type=Path, default=DEFAULT_GOLDEN)
    score_cmd.add_argument("--disabled", type=Path)
    score_cmd.add_argument("--output", type=Path)
    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    try:
        if args.command == "prepare":
            result = prepare(
                args.bundle, suite=args.suite, prompts=args.prompts,
                attempt_root=args.attempt_root,
                development_root=args.development_root,
            )
        elif args.command == "collect":
            run_collect(
                args.bundle, args.attempt_root, search_interval=args.search_interval,
                development_root=args.development_root,
            )
            return 0
        elif args.command == "summarize":
            result = summarize_attempt(args.attempt, mapping_path=args.mapping, suite=args.suite)
        else:
            result = score(
                args.collect, mapping_path=args.mapping, golden=args.golden,
                disabled_path=args.disabled,
            )
            if args.output:
                _write_json_new(args.output, result)
    except (OSError, ValueError, TypeError, json.JSONDecodeError, ImportError) as exc:
        print(json.dumps({
            "ok": False, "error": type(exc).__name__, "message": str(exc),
        }, ensure_ascii=False), file=sys.stderr)
        return 2
    print(json.dumps(result, ensure_ascii=False, indent=2))
    if args.command == "score" and not (result.get("capability_gate") or {}).get("passed"):
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
